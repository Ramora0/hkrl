"""Generates sim/hero/hero_fields.h (X-macro lists) from the recorded trace header and the hero dump.

    python sim/hero/gen_fields.py

Sources: analysis/traces/p0/r2_move.a.hktrace header fields.hero / fields.cstate / fields.playerdata
(docs/trace-format.md #Header: every primitive HeroController field, declaration order) and
analysis/dumps/GG_Hornet_1/hero.json (System.Boolean vs Int32/enum so bools get a 'b' code).
The PlayerData subset is the set of keys HeroController reads or writes (grep over HeroController.cs
for GetBool/GetInt/SetIntSwappedArgs/SetBoolSwappedArgs + the PlayerData methods it calls).
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)
from hkpy.hktrace import read_trace  # noqa: E402

# PlayerData keys HeroController touches (grep HeroController.cs) + keys the PlayerData methods it calls
# touch (PlayerData.cs TakeHealthInternal:8582-8614, orig_AddHealth:8629-8643, MaxHealth:4630-4636,
# orig_UpdateBlueHealth:8616-8627, AddMPCharge:4779-4813, TakeMP:4815-4829, CurrentMaxHealth:3084-3094,
# SetHazardRespawn:5069-5080).
PD_KEYS = """
health maxHealth maxHealthBase healthBlue joniHealthBlue damagedBlue prevHealth blockerHits
MPCharge maxMP MPReserve MPReserveMax soulLimited focusMP_amount
disablePause isInvincible invinciTest infiniteAirJump overcharmed betaEnd permadeathMode
hasDash canDash hasWalljump canWallJump hasDoubleJump hasSuperDash hasShadowDash hasDreamNail hasNailArt
hasAcidArmour hasLantern canBackDash hasDreamGate atBench respawnType environmentType grimmChildLevel
hazardRespawnFacingRight brokenCharm_23 killedBlocker killsBlocker
""".split() + ["equippedCharm_%d" % i for i in range(1, 41)]


def main():
    t = read_trace(os.path.join(ROOT, "analysis", "traces", "p0", "r2_move.a.hktrace"))
    h = t.header["fields"]
    hero = json.load(open(os.path.join(ROOT, "analysis", "dumps", "GG_Hornet_1", "hero.json")))
    hc = {e["name"]: e for e in hero["heroController"]}
    pd_types = {e["name"]: e["type"] for e in h["playerdata"]}
    pdj = json.load(open(os.path.join(ROOT, "analysis", "dumps", "GG_Hornet_1", "playerdata.json")))
    pd_clr = {e["name"]: e["type"] for e in pdj["fields"]}   # CLR types (System.Boolean / System.Int32 / ...)
    out = []
    out.append("/* GENERATED by sim/hero/gen_fields.py -- do not edit.")
    out.append(" * Sources: analysis/traces/p0/r2_move.a.hktrace header fields.hero / fields.cstate / fields.playerdata")
    out.append(" *          (docs/trace-format.md #Header), analysis/dumps/GG_Hornet_1/hero.json (field CLR types).")
    out.append(" * X(ctype, cname, \"trace name\", code)   code: 'f' float32, 'i' int32/enum, 'b' bool (i32 on the wire). */")
    out.append("#define HERO_FIELDS(X) \\")
    for e in h["hero"]:
        n, ty = e["name"], e["type"]
        cname = n.replace("<fallTimer>k__BackingField", "fallTimer")
        dtype = hc[n]["type"] if n in hc else None
        if ty == "f32":
            ct, code = "float", "f"
        elif dtype == "System.Boolean":
            ct, code = "uint8_t", "b"
        else:
            ct, code = "int32_t", "i"
        out.append("    X(%s, %s, \"%s\", '%s') \\" % (ct, cname, n, code))
    out[-1] = out[-1].rstrip(" \\")
    out.append("")
    out.append("/* HeroControllerStates public bool fields; bit i of FRAME.cstate = field i")
    out.append(" * cite: analysis/decomp/Assembly-CSharp/HeroControllerStates.cs:7-115 ; docs/trace-format.md #Header */")
    out.append("#define HERO_CSTATE(X) \\")
    for n in h["cstate"]:
        out.append("    X(%s) \\" % n)
    out[-1] = out[-1].rstrip(" \\")
    out.append("")
    out.append("/* PlayerData fields HeroController reads/writes (subset of the 1443 traced; same names) */")
    out.append("#define HERO_PD_FIELDS(X) \\")
    missing = [k for k in PD_KEYS if k not in pd_types]
    if missing:
        raise SystemExit("PD keys not in trace header: %r" % missing)
    for k in PD_KEYS:
        ty = pd_types[k]
        if ty == "f32":
            ct, code = "float", "f"
        elif pd_clr.get(k) == "System.Boolean":
            ct, code = "uint8_t", "b"
        else:
            ct, code = "int32_t", "i"
        out.append("    X(%s, %s, \"%s\", '%s') \\" % (ct, k, k, code))
    out[-1] = out[-1].rstrip(" \\")
    out.append("")
    path = os.path.join(ROOT, "sim", "hero", "hero_fields.h")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path, len(h["hero"]), "hero fields,", len(h["cstate"]), "cstate bits,", len(PD_KEYS), "pd fields")
    gen_dump_init(h, hero, pdj, pd_clr)


def c_float(v):
    s = "%.9g" % float(v)
    if "." not in s and "e" not in s and "n" not in s:
        s += ".0"
    return s + "f"


